#!/usr/bin/env node
/**
 * Regenerates the airports INSERT in supabase/seed.sql from the single source
 * of truth, apps/web/src/lib/airports.ts.
 *
 * The seed previously carried MIA only, so every route line and airport marker
 * for a second airport resolved to nothing. Run this after editing AIRPORTS:
 *
 *   node scripts/generate-airport-seed.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(resolve(root, "apps/web/src/lib/airports.ts"), "utf8");

const entries = [
  ...src.matchAll(
    /\{\s*iata:\s*"([A-Z0-9]{3})",\s*icao:\s*"([A-Z0-9]{4})",\s*name:\s*"([^"]+)",\s*city:\s*"([^"]+)",\s*country:\s*"([^"]+)",\s*lat:\s*(-?[\d.]+),\s*lon:\s*(-?[\d.]+),\s*tz:\s*"([^"]+)"/g
  ),
].map(([, iata, icao, name, city, country, lat, lon, tz]) => ({
  iata,
  icao,
  name,
  city,
  country,
  lat,
  lon,
  tz,
}));

if (entries.length === 0) {
  console.error("No airport entries parsed from airports.ts — did its shape change?");
  process.exit(1);
}

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const values = entries
  .map((a) => `  (${[q(a.iata), q(a.icao), q(a.name), q(a.city), q(a.country), a.lat, a.lon, q(a.tz)].join(", ")})`)
  .join(",\n");

const block = `-- Seed: airports
-- GENERATED by scripts/generate-airport-seed.mjs from
-- apps/web/src/lib/airports.ts — edit that file, then re-run the script.
-- ${entries.length} airports: MIA, surrounding Florida/Bahamas/Cuba fields, and
-- major MIA destinations (needed for route lines and airport markers).
INSERT INTO airports (iata_code, icao_code, name, city, country, latitude, longitude, timezone)
VALUES
${values}
ON CONFLICT (iata_code) DO UPDATE SET
  icao_code = EXCLUDED.icao_code,
  name = EXCLUDED.name,
  city = EXCLUDED.city,
  country = EXCLUDED.country,
  latitude = EXCLUDED.latitude,
  longitude = EXCLUDED.longitude,
  timezone = EXCLUDED.timezone;`;

const seedPath = resolve(root, "supabase/seed.sql");
let seed = readFileSync(seedPath, "utf8");

const marker = /-- Seed: (MIA airport|airports)[\s\S]*?;\n/;
if (!marker.test(seed)) {
  console.error("Could not locate the airports seed block in supabase/seed.sql");
  process.exit(1);
}
seed = seed.replace(marker, `${block}\n`);
writeFileSync(seedPath, seed);

console.log(`Wrote ${entries.length} airports to supabase/seed.sql`);
